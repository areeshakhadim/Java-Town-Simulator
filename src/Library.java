    private void issueBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_issueBookActionPerformed
        // TODO add your handling code here:
            int selectedRow = books.getSelectedRow();

    if (selectedRow != -1) {
        String bookName = books.getValueAt(selectedRow, 0).toString();

        if (issuedBooks.contains(bookName)) {
            JOptionPane.showMessageDialog(this, "This book is already issued.", "Duplicate Issue", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (bookQueue.size() < 4) {
            String issueDate = LocalDate.now().format(DateTimeFormatter.ofPattern("dd-MM-yyyy"));
            String dueDate = LocalDate.now().plusDays(14).format(DateTimeFormatter.ofPattern("dd-MM-yyyy"));
            IssuedBook issuedBook = new IssuedBook(bookName, issueDate, dueDate);

            bookQueue.offer(issuedBook);
            issuedBooks.add(bookName);

            // Add only the book name (without the due date) to list1
            list1.add(bookName);

            // Update button states
            updateButtonStates();

            // Enable the Next button if 4 books are issued
            if (bookQueue.size() == 4) {
                jButton2.setEnabled(true);
                JOptionPane.showMessageDialog(this, "You have issued the maximum of 4 books. You can now proceed to the next step.", 
                                              "Limit Reached", JOptionPane.INFORMATION_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "You can only issue 4 books.", "Limit Reached", JOptionPane.WARNING_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "Please select a book to issue.", "No Selection", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_issueBookActionPerformed
     private void displayBookDetails() {
        int selectedIndex = list1.getSelectedIndex();
        if (selectedIndex != -1) {
            String selectedBook = list1.getItem(selectedIndex);
            String bookName = selectedBook.split(" \\(Due:")[0];

            // Find the IssuedBook object in the queue
            for (IssuedBook book : bookQueue) {
                if (book.bookName.equals(bookName)) {
                    JOptionPane.showMessageDialog(this, "Book: " + book.bookName + "\nIssue Date: " + book.issueDate + "\nDue Date: " + book.dueDate,
                            "Book Details", JOptionPane.INFORMATION_MESSAGE);
                    break;
                }
            }
        }
    }
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (!bookQueue.isEmpty()) {
        // Get the first book in the queue (the one that was added first)
        IssuedBook firstBook = bookQueue.poll(); // Removes and returns the first book
        
        // Remove the book from the issuedBooks set
        issuedBooks.remove(firstBook.bookName);
        
        // Remove the book from the list1 (GUI list)
        list1.remove(firstBook.bookName);
        
        // Show a success message
        JOptionPane.showMessageDialog(this, "Book removed successfully: " + firstBook.bookName, "Success", JOptionPane.INFORMATION_MESSAGE);

        // Update button states
        updateButtonStates();

        // Disable the Next button if less than 4 books are issued
        if (bookQueue.size() < 4) {
            jButton2.setEnabled(false);
        }
    } else {
        JOptionPane.showMessageDialog(this, "No books to remove.", "No Books", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

