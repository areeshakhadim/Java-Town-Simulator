 private void loadBooks() {
         DefaultTableModel model = (DefaultTableModel) books.getModel();
        model.setRowCount(0); // Clear existing rows

        String[] bookNames = {
            "Clean Code by Robert C. Martin",
            "Introduction to Algorithms by CLRS",
            "The Pragmatic Programmer by Andy Hunt",
            "Design Patterns by Erich Gamma",
            "Head First Java by Kathy Sierra",
            "Effective Java by Joshua Bloch",
            "Artificial Intelligence by Stuart Russell",
            "Computer Networks by Andrew Tanenbaum",
            "Operating System Concepts by Silberschatz",
            "Data Structures and Algorithms in Java by Lafore"
        };

        for (String book : bookNames) {
            model.addRow(new Object[]{book});
        }
    }

