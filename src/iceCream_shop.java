     private void updateCartTable() {
        // Update the table with cart data
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);  // Clear existing rows

    for (CartItem item : cart) {
        model.addRow(new Object[]{item.flavor, item.quantity, item.price, item.total});
    }
    }
    /**
     * @param args the command line arguments
     */
    private void updatePriceLabel() {
    String selectedFlavor = flavorlist.getSelectedValue();
    if (selectedFlavor != null) {
        double price = flavorPrices.get(selectedFlavor);
        jLabel2.setText("Price: $" + String.format("%.2f", price));
    }
}

