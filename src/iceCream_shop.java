public class CartItem {
    String flavor;
    double price;
    int quantity;
    double total;

    public CartItem(String flavor, double price, int quantity) {
        this.flavor = flavor;
        this.price = price;
        this.quantity = quantity;
        updateTotal();
    }

    public void updateQuantity(int quantity) {
        this.quantity = quantity;
        updateTotal();
    }

    public void updateTotal() {
        this.total = price * quantity;
    }
}

    
