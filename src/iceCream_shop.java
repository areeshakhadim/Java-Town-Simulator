    private void icecartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_icecartActionPerformed
        // TODO add your handling code here:
         String selectedFlavor = flavorlist.getSelectedValue();
    if (selectedFlavor == null) {
        return; // No flavor selected
    }

    // Check if the flavor is already in the cart
    if (cart.size() >= 3) {
        javax.swing.JOptionPane.showMessageDialog(this, "You can only add 3 different flavors.");
        return;
    }

    for (CartItem item : cart) {
        if (item.flavor.equals(selectedFlavor)) {
            javax.swing.JOptionPane.showMessageDialog(this, "You already have this flavor in your cart.");
            return;
        }
    }

    double price = flavorPrices.get(selectedFlavor);
    cart.add(new CartItem(selectedFlavor, price, 1));
    updateCartTable();

    // Disable Add to Cart button if the cart size reaches 3
    if (cart.size() == 3) {
        icecart.setEnabled(false);
        javax.swing.JOptionPane.showMessageDialog(this, "You have added the maximum of 3 ice creams.", 
                                                  "Cart Full", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }
    }//GEN-LAST:event_icecartActionPerformed

    private void addicecreamActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addicecreamActionPerformed
        // TODO add your handling code here:
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow >= 0) {
            CartItem item = cart.get(selectedRow);
            item.updateQuantity(item.quantity + 1);
            updateCartTable();
        }
    }//GEN-LAST:event_addicecreamActionPerformed

    private void minusicecreamActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_minusicecreamActionPerformed
        // TODO add your handling code here:
       int selectedRow = jTable1.getSelectedRow();
        if (selectedRow >= 0) {
            CartItem item = cart.get(selectedRow);
            if (item.quantity > 1) {
                item.updateQuantity(item.quantity - 1);
                updateCartTable();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot decrease below 1.");
            }
        }
    }//GEN-LAST:event_minusicecreamActionPerformed

    private void checkoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkoutActionPerformed
        // TODO add your handling code here:
    if (cart.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Your cart is empty. Please add at least one item before checking out.");
        return;
    }

    // Calculate the total price
    double total = 0;
    for (CartItem item : cart) {
        total += item.total; // Add the total of each cart item
    }

    // Update the total price label
    totalprice.setText("Total Price: $" + String.format("%.2f", total));

    // Disable all buttons after checkout
    disableAllButtons();
    jButton1.setEnabled(true);

    // Show a confirmation message
    javax.swing.JOptionPane.showMessageDialog(this, "Checkout completed successfully!", 
                                              "Checkout Complete", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_checkoutActionPerformed

