     // Method to add items to the tree
    private void addItem(String itemName, double price) {
        ItemNode newNode = new ItemNode(itemName, price);
        ItemNode current = root;
        while (current.next != null) {
            current = current.next;
        }
        current.next = newNode;
    }
    
     // Method to update the JComboBox with the items in the tree
    private void updateComboBox() {
        LinkedList<String> itemList = new LinkedList<>();
        ItemNode current = root;
        while (current != null) {
            itemList.add(current.itemName);
            current = current.next;
        }
        Menu.setModel(new DefaultComboBoxModel<>(itemList.toArray(new String[0])));
    }

     // Method to get the price of an item by name
    private double getPrice(String itemName) {
        ItemNode current = root;
        while (current != null) {
            if (current.itemName.equals(itemName)) {
                return current.price;
            }
            current = current.next;
        }
        return 0.0;
    }

