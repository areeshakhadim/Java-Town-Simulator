    private void addToCartButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addToCartButtonActionPerformed
        // TODO add your handling code here:                                                
 if (isCheckoutComplete) {
        JOptionPane.showMessageDialog(this, "Checkout already completed. You cannot add more items.");
        return;
    }

    // Get the selected item from the ComboBox
    String selectedItem = (String) Menu.getSelectedItem();
    double price = getPrice(selectedItem);

    // Check if the cart is full
    if (cart.size() >= 4) {
        JOptionPane.showMessageDialog(this, "Cart is full. You can only add up to 4 items.");
        return;
    }

    // Check if the item is already in the cart
    for (Item item : cart) {
        if (item.itemName.equals(selectedItem)) {
            JOptionPane.showMessageDialog(this, "Item already added.");
            return;
        }
    }

    // Add the selected item to the stack (cart)
    cart.push(new Item(selectedItem, price));

    // Update the cart table
    updateCartTable();
    }//GEN-LAST:event_addToCartButtonActionPerformed

    private void decreaseitemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_decreaseitemActionPerformed
        // TODO add your handling code here:
    int selectedRow = cartTable.getSelectedRow();
        if (selectedRow != -1) {
            String selectedItem = (String) cartTable.getValueAt(selectedRow, 0);
            for (Item item : cart) {
                if (item.itemName.equals(selectedItem)) {
                    if (item.quantity > 1) {
                        item.quantity--;
                    }
                    break;
                }
            }
            // Update the cart table
            updateCartTable();
        }
    }//GEN-LAST:event_decreaseitemActionPerformed

    private void increaseitemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_increaseitemActionPerformed
        // TODO add your handling code here:
     int selectedRow = cartTable.getSelectedRow();
        if (selectedRow != -1) {
            String selectedItem = (String) cartTable.getValueAt(selectedRow, 0);
            for (Item item : cart) {
                if (item.itemName.equals(selectedItem)) {
                    item.quantity++;
                    break;
                }
            }
            // Update the cart table
            updateCartTable();
        }
    }//GEN-LAST:event_increaseitemActionPerformed
// Method to update the cart table with the latest cart contents
    private void updateCartTable() {
        // Clear the existing table rows
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) cartTable.getModel();
        model.setRowCount(0);

        // Add the items from the stack to the table
        for (Item item : cart) {
            model.addRow(new Object[]{item.itemName, item.price, item.quantity, item.price * item.quantity});
        }

        // Disable the decrease button if the selected item's quantity is 1
        int selectedRow = cartTable.getSelectedRow();
        if (selectedRow != -1) {
            int quantity = (int) cartTable.getValueAt(selectedRow, 2);
            decreaseitem.setEnabled(quantity > 1);
        }
    }
    private void checkOutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkOutActionPerformed
        // TODO add your handling code here:
    if (isCheckoutComplete) {
        JOptionPane.showMessageDialog(this, "Checkout already completed. You cannot add more items.");
        return;
    }

    if (cart.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Your cart is empty. Please add at least one item before checking out.");
        return;
    }

    // Calculate the total price by iterating through the cart
    double total = 0.0;
    for (Item item : cart) {
        total += item.price * item.quantity; // Add price * quantity for each item
    }

    // Update the total price label to show the total
    totalprice.setText("Total Price: " + total + "$");
    
    // Set checkout as complete
    isCheckoutComplete = true;

    // Disable cart and checkout buttons
    addToCartButton.setEnabled(false);
    checkOut.setEnabled(false);
    increaseitem.setEnabled(false);
    decreaseitem.setEnabled(false);
    
    // Enable the "Next" button after successful checkout
    jButton2.setEnabled(true);

    

    JOptionPane.showMessageDialog(this, "Checkout completed successfully!");

    }//GEN-LAST:event_checkOutActionPerformed

